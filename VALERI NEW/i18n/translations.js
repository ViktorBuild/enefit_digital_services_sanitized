/* ── Language Manager ── */
const Lang = (() => {
  const LANG_KEY = 'valeri_lang';

  function get() {
    return localStorage.getItem(LANG_KEY) || 'de';
  }

  function set(lang) {
    localStorage.setItem(LANG_KEY, lang);
    document.documentElement.lang = lang;
  }

  /** Translate key, optionally interpolating {0}, {1} … placeholders */
  function t(key, ...args) {
    const lang = get();
    const dict = Translations[lang] || Translations['de'];
    let str = dict[key] ?? Translations['de'][key] ?? key;
    args.forEach((val, i) => { str = str.replace(`{${i}}`, val); });
    return str;
  }

  function isDE() { return get() === 'de'; }
  function isEN() { return get() === 'en'; }

  return { get, set, t, isDE, isEN };
})();

/* Expose globally */
window.Lang = Lang;
window.T = Lang.t;
